import * as vscode from 'vscode';

export type Lang = 'es' | 'en';

/** Idioma de Aura: el del ajuste aura.language, o el de VS Code si está en "auto". */
export function getLang(): Lang {
    const setting = vscode.workspace.getConfiguration('aura').get<string>('language', 'auto');
    if (setting === 'es' || setting === 'en') {
        return setting;
    }
    return vscode.env.language.toLowerCase().startsWith('es') ? 'es' : 'en';
}

