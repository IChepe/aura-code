const MESSAGES: Record<Lang, Record<MessageKey, string>> = { es, en };

/** Texto traducido; {0}, {1}… se reemplazan por los argumentos. */
export function t(key: MessageKey, ...args: (string | number)[]): string {
    const text = MESSAGES[getLang()][key] ?? es[key];
    return text.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}

/** Todos los textos con un prefijo (para enviarlos a las webviews). */
export function messages(prefix: string): Record<string, string> {
    const dict = MESSAGES[getLang()];
    return Object.fromEntries(Object.entries(dict).filter(([k]) => k.startsWith(prefix)));
}
